#pragma once

#define CPU_FREQ_DEVICE_TYPE 0x8000
#define CPU_FREQ_IOCTL_GET_FREQUENCIES \
    CTL_CODE(CPU_FREQ_DEVICE_TYPE, 0x800, METHOD_BUFFERED, FILE_READ_ACCESS)

#define CPU_FREQ_PROTOCOL_VERSION 0x00010000u

typedef struct _CPU_FREQ_ENTRY {
    UINT16 Group;
    UINT16 Valid;
    UINT32 Processor;
    UINT32 FrequencyMHz;
    UINT32 Ratio;
    UINT64 PerfStatus;
} CPU_FREQ_ENTRY, *PCPU_FREQ_ENTRY;

typedef struct _CPU_FREQ_RESPONSE {
    UINT32 Size;
    UINT32 Version;
    UINT32 ProcessorCount;
    UINT32 BusFrequencyMHz;
    UINT32 FailedReads;
    UINT32 Reserved;
    CPU_FREQ_ENTRY Entries[1];
} CPU_FREQ_RESPONSE, *PCPU_FREQ_RESPONSE;

#define CPU_FREQ_RESPONSE_HEADER_SIZE FIELD_OFFSET(CPU_FREQ_RESPONSE, Entries)
